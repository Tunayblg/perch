import AppKit

struct ClipItem: Identifiable, Equatable {
    let id = UUID()
    let text: String
    var date = Date()
}

/// Pano geçmişi. Gizlilik için yalnızca bellekte tutulur (diske yazılmaz, uygulama kapanınca silinir).
/// Parola yöneticilerinin "gizli" işaretlediği kopyalar kaydedilmez.
final class ClipboardService: ObservableObject {
    @Published private(set) var items: [ClipItem] = []
    @Published private(set) var lastCopiedID: UUID?

    private let maxItems = 20
    private let maxLength = 2000
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var timer: Timer?

    private let sensitiveTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
    ]

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 1.0, repeats: true) { [weak self] _ in self?.poll() }
        timer?.tolerance = 0.4
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount

        if let types = pb.types, !sensitiveTypes.isDisjoint(with: types) { return }
        guard let raw = pb.string(forType: .string) else { return }
        let text = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !text.isEmpty else { return }
        insert(String(text.prefix(maxLength)))
    }

    private func insert(_ text: String) {
        items.removeAll { $0.text == text }
        items.insert(ClipItem(text: text), at: 0)
        if items.count > maxItems { items.removeLast(items.count - maxItems) }
    }

    /// Satıra tıklayınca metni tekrar panoya koyar.
    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(item.text, forType: .string)
        lastChangeCount = pb.changeCount
        lastCopiedID = item.id
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.2) { [weak self] in
            if self?.lastCopiedID == item.id { self?.lastCopiedID = nil }
        }
    }

    func remove(_ id: UUID) {
        items.removeAll { $0.id == id }
    }

    func clear() {
        items.removeAll()
    }
}
